/**
 * 活動規範的內容。
 *
 * 這一份餵兩個地方，所以不會各改各的：
 *   - 編輯器開場的「活動規範」卡片 → TERMS_RULES（摘要版，只有條列）
 *   - /terms 頁 → TERMS_SECTIONS（完整版，也是 LINE Developers 後台
 *     「Terms of use URL」要填的那一頁）
 *
 * ## 參加門檻：登入即可，沒有消費門檻
 *
 * 2026-09-24 確認的活動設計。舊版規範寫的「消費達 599 元獲得便利貼」與
 * 「30 分鐘內送出」是店內 QR code（token）那一套 —— 店員結帳時發一張
 * 30 分鐘有效的 token，沒有 token 就送不出去。那個機制已經退場，
 * 改成 LINE 登入，兩條規則也一併拿掉。
 *
 * 所以現在的門檻只有一個：**有 LINE 帳號就能送**。
 * `system/editor_token_requirement` 維持 `enabled: false`；
 * 哪天要把消費門檻加回來，得先重新啟用 token 機制，這份文案也要跟著改。
 *
 * ## 刻意不寫的東西（2026-10-13 盤點）
 *
 * - **地址、電話**：法律沒有要求，有一個聯絡管道（email）就夠。客戶要公開再加。
 * - **活動起訖日**：活動是常設的，寫「即日起至公告結束」，結束時改這一行並在網站公告。
 * - **社群／宣傳素材的使用授權**：只授權 LED 牆與活動網站。客戶要把便利貼轉貼到 IG 等社群，
 *   第六條要加回去 —— 沒寫就用，等於超出顧客同意的範圍。
 *
 * ## 刻意避開的寫法（2026-10-13 檢查）
 *
 * - **不寫「審核通過後展示」**：實際上只有自動的文字檢查（而且服務出錯時放行），送出就排隊上牆，
 *   沒有人工先審。寫了審核，不當內容上牆時就變成「你們說有審核」。只寫「違規的會被撤下」。
 *   也不寫「只檢查文字」：等於告訴想搗亂的人畫圖不會被擋。
 * - **不寫「保有最終解釋權」**：消保單位認為這種約款在定型化契約裡可能無效，也是常見的批評點。
 *   改寫「是否違規由本公司依本規範判斷」，意思一樣、範圍限縮在違規認定。
 * - **不寫固定秒數、不承諾每張都會展示**：放大幾秒是大螢幕網址參數（duration），店裡可以改。
 * - **著作權分開寫**：顧客畫的、寫的歸顧客，貼紙、造型、背景是店家的素材，不能寫成整張都歸顧客。
 * - **冒名**：署名用的是 LINE 暱稱，使用者自己改得到，改成店長或藝人的名字就能冒名上牆，所以列進禁止事項。
 * - **簡體字照擋，但寫成書寫規則**（2026-10-13 使用者決定繼續擋）：寫在規範裡、被擋時另有說法
 *   （editor 的 textSimplified），不跟違規內容混在一起講「不妥適」。審核那邊見 moderation.post.ts 的 SIMP
 *
 * ## 停權門檻的數字
 *
 * 「被撤下累計 3 次」是程式裡寫死的 STRIKE_LIMIT（app/types/index.ts），
 * 後台下架第 3 張時自動停權。改那個數字要回來改這裡兩處與三份翻譯。
 * 「情節重大者得逕行停止」對應的是會員面板的手動封鎖，不必等累計。
 *
 * ## 投稿上限的數字
 *
 * 下面寫的「5 分鐘 / 3 張」與後台「上傳控管 → 投稿頻率限制」是分開的兩件事：
 * 後台改了設定，**這裡的文字不會跟著動**。改設定時記得回來改這一行，
 * 否則規範就與實際行為不符。
 */

